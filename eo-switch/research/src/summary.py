# ------------------------------------------------------------------ step 3
w('## 2. Populations')
w('')
w('P2 from the EOs of uniform scrambles is the same as from uniform EO-solved states: after a linear EO chosen from the edge orientation alone the state is uniform over the EO-solved states (eo-to-dr WRITEUP 5); the RZP weights are exact counts of canonical EO-keeping sequences that reach their DRM for the first time (`eoswtools rzp`; the EO taken to end in F or in B, which fixes which half turn may start the RZP).')
