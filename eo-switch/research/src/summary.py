    w(f"| {nm} | {f3(a['p_le6'])} | {f3(b['p_le6'])} | {f3(c['p_le6'])} | {f3(e5['p_le6'])} | {int(float(e5['weight_or_attempts'])):,} | {f3(e6['p_le_11minusL'])} | {int(float(e6['weight_or_attempts'])):,} |")
