w('Sub-7 share by DRM. P2 = an RZP of 5 turns from a uniform EO-solved state, weighted by the number of ways (exact); "same side" = the RZP\'s end state, "switched" = its inverse. '
  'P3 = the sampled attempts at total length 5 (EO + RZP = 5) and 6; for length 6 the target is DR in 5 (11 - 6).')
