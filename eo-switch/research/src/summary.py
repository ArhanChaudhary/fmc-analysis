#!/usr/bin/env python3
"""Write out/SUMMARY.md from the files in out/.  Tables are generated; the few numbers quoted in the prose of the
short version were read from those files (out/q4.tsv, out/search_top.tsv, out/populations.tsv)."""
import os, sys, csv, json, collections
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import pop, explain, search
OUT = pop.OUT
def tsv(name): return list(csv.DictReader(open(os.path.join(OUT, name)), delimiter='\t'))
def f3(x): return f'{float(x):.3f}'
def pct(x, k=1): return f'{100 * float(x):.{k}f}%'
F = pop.feat(); d = F['d'].astype(int); P = pop.populations()
