#!/usr/bin/env python3
"""Writes EOSwitch/CardsRef.lean: the exact integers of the v2 switch cards as the research computed them, in Lean
literals, so that no number of CardsThm.lean is typed by hand.

    research/v2/out/results.json   results.py   per DRM, the card's groups in order: label, verdict and
                                                [states, DR in 4 or less, in 5, in 6, in 7, longer]
    research/v2/cards.py           CARDS, BASE  the same groups as sets of cosets (checked here against results.json),
                                                and the switch sets: the card, the card with its "time" groups, and
                                                every current policy.  For each: [states switched, DR in 4 or less
                                                not switched, in 5 not switched, in 6 not switched, switched with a
                                                DR of 7 or longer]  (results.json keeps these as shares)
    research/out/big/feat.npz, research/v2/out/feat2.npz   the reads the cards add, on the worked examples of
                                                features.py (the 27 states of the certificate's `feature_examples`)

Run from this directory, with the project's Python:
    source /data/fmc/env.sh; python3 gen_cards.py     (rerun after cards.py / results.py; if a number changed, the build fails)"""
import os, sys, json
here = os.path.dirname(os.path.abspath(__file__))
V2 = os.path.join(here, '..', '..', 'research', 'v2'); SRC = os.path.join(here, '..', '..', 'research', 'src')
sys.path.insert(0, V2); sys.path.insert(0, SRC)
import numpy as np
import lib, cards, rules, features
from lib import F, d, drm_mask, N0

R = json.load(open(os.path.join(V2, 'out', 'results.json')))
DRMS = [(4, 4), (4, 2), (3, 2), (7, 8), (8, 8), (2, 2), (4, 6), (3, 4), (3, 6), (5, 4), (5, 6), (6, 6)]
assert list(cards.CARDS.keys()) == DRMS and list(R['drm'].keys()) == [f'{c}c{e}e' for c, e in DRMS]

def nat(x):
    x = int(x); assert x >= 0, x
    return str(x)
def lst(l): return '[' + ', '.join(nat(x) for x in l) + ']'
def s(x):
    assert '"' not in x and '\\' not in x, x
    return '"' + x + '"'
def row(g):
    """[states, DR in 4 or less, in 5, in 6, in 7, longer] of a set of cosets."""
    h = np.bincount(d[g], minlength=12)
    return [int(g.sum()), int(h[:5].sum()), int(h[5]), int(h[6]), int(h[7]), int(h[8:].sum())]
def pol(m, sw):
    """[switched, DR <= 4 not switched, DR 5 not switched, DR 6 not switched, switched with DR >= 7] within the DRM m."""
    sw = sw & m; no = m & ~sw
    return [int(sw.sum()), int((no & (d <= 4)).sum()), int((no & (d == 5)).sum()), int((no & (d == 6)).sum()), int((sw & (d >= 7)).sum())]

L = ['/-',
     '  EOSwitch.CardsRef — GENERATED by `gen_cards.py`, do not edit: the exact integers of the v2 switch cards as the',
     '  research computed them (research/v2/out/results.json and the sets of research/v2/cards.py).  Only',
     '  CardsThm.lean reads it: each theorem there named `…_matches_study` says that what Lean counts from its own',
     '  definitions equals one of these tables.',
     '  A group row is [states, DR in 4 or less, DR in 5, DR in 6, DR in 7, DR longer than 7].',
     '  A policy row is [states switched, DR in 4 or less not switched, DR in 5 not switched, DR in 6 not switched,',
     '  switched with a DR of 7 or longer].',
     '-/', '', 'namespace EOSwitch', 'namespace cardsref', '']
def add(doc, name, typ, body): L.extend([f'/-- {doc} -/', f'def {name} : {typ} :=', '  ' + body, ''])

tot, grp, pols = [], [], []
for (c, e) in DRMS:
    m = drm_mask(c, e); X = R['drm'][f'{c}c{e}e']
    tot.append(f'({c}, {e}, {lst(row(m))})')
    assert X['n'] == int(m.sum()) and [X['n_le4'], X['n_d5'], X['n_d6']] == row(m)[1:4]
    G = cards.CARDS[(c, e)]
    assert len(G) == len(X['groups'])
    rows = []
    cover = np.zeros(N0, bool)
    for (label, g, v), j in zip(G, X['groups']):
        r = [j['n'], j['le4'], j['d5'], j['d6'], j['d7'], j['longer']]
        assert (label, v) == (j['label'], j['verdict']) and r == row(g), (c, e, label)      # results.json = the sets of cards.py
        assert not (cover & g).any(); cover |= g
        rows.append(f'({s(label)}, {s(v)}, {lst(r)})')
    assert (cover == m).all()
    grp.append(f'({c}, {e},\n    [' + ',\n     '.join(rows) + '])')
    ps = [('card', cards.card_mask((c, e))), ('card+time', cards.card_mask((c, e), ('switch', 'time')))]
    ps += [(key, sw) for key, name, who, sw in cards.BASE[(c, e)]]
    # the shares of results.json are these integers over the DRM's totals
    for key, sw in ps:
        j = X['card'] if key == 'card' else X['card_time'] if key == 'card+time' else X['base'][key]
        p = pol(m, sw); n = int(m.sum())
        assert abs(j['switch'] - p[0] / n) < 1e-12 and abs(j['wasted'] - p[4] / n) < 1e-12
        for q, k in ((1, 'le4'), (2, 'd5'), (3, 'd6')):
            assert abs(j['miss_' + k] - (p[q] / X['n_' + k] if X['n_' + k] else 0)) < 1e-12, (c, e, key)
    pols.append(f'({c}, {e},\n    [' + ',\n     '.join(f'({s(key)}, {lst(pol(m, sw))})' for key, sw in ps) + '])')
add('Per DRM (c, e): all its states as a group row.', 'TOTALS', 'List (Nat × Nat × List Nat)', '[' + ',\n   '.join(tot) + ']')
add('Per DRM (c, e): the groups of its card, in the card\'s order: (label, verdict, group row).', 'GROUPS',
    'List (Nat × Nat × List (String × String × List Nat))', '[' + ',\n   '.join(grp) + ']')
add('Per DRM (c, e): (switch set, policy row) for the card ("card": its switch groups), the card with its "time" groups '
    '("card+time") and each current policy, by the key cards.py gives it in BASE.', 'POLICIES',
    'List (Nat × Nat × List (String × List Nat))', '[' + ',\n   '.join(pols) + ']')

# the reads the cards add, on the worked examples of features.py (same list as the certificate's feature_examples)
EX = [(True, 'R'), (True, 'R U'), (False, "U' F2 B2 R2 U2 R"), (False, 'D F2 B2 L2 U2 R'), (False, 'R F2 U2 R'), (False, "U' R2 D B2 R"),
      (False, "D R' U2 F2 R"), (False, "U' R2 D R2 D L"), (False, "R2 U D' F2 L"), (False, "R' U2 F2 L2 U R"), (False, "R U2 B2 R2 D' R"),
      (False, 'U B2 D2 L D R'), (False, "D L U R2 U' R"), (False, "D' L' D L2 D' R"), (False, 'R'), (False, "U' R"), (False, "U' R2 U R"),
      (False, 'U F2 R'), (False, 'D F2 B2 R'), (False, 'F2 B2 R'), (False, 'R U2 R'), (False, 'R U R'), (False, 'R U L'), (False, 'R L'),
      (False, 'R U2 L'), (True, "R U D2 L U' R U2"), (True, "R U D2 L U' R U2 L'")]
DF = rules.dfbr(F)
def reads(ix):
    cc = int(F['corner_case'][ix]); suf = int(F['case_suffix'][ix]); hc = int(F['hole_cfg'][ix])
    return [int(F['edges_paired'][ix]), 4 if cc < 0 else cc, 7 if suf < 0 else suf, 3 if hc < 0 else hc, int(F['ud_split'][ix]),
            int(F['edges_same_layer'][ix]), int(F['split_pairs'][ix]), int(DF[ix]), int(F['a_one_from_d'][ix]), int(F['anti_ar'][ix]),
            int(F['cols_bad'][ix])]
ex = []
for after, seq in EX:
    ix = features.state_after(seq) if after else features.state_solved_by(seq)
    ex.append(f"({'true' if after else 'false'}, {s(seq)}, {lst(reads(ix))})")
add('The reads the cards add, on the 27 worked examples of the research (the state after the sequence if the flag is '
    'true, the state the sequence solves otherwise): [paired edges, corner case (0 a, 1 b, 2 c, 3 d, 4 = not 4 bad '
    'corners), suffix (7 = not 4 bad corners), holes (0 on one R/L face, 1 diagonal, 2 on one F/B face, 3 = not two '
    'holes), corners per layer (the larger count), bad edges in one layer, split pairs, one of the 12 "D F2 B2 R" '
    'cases, 4a one U/D turn from 4d, anti-AR, columns with both corners bad].', 'EXAMPLES', 'List (Bool × String × List Nat)', '[' + ',\n   '.join(ex) + ']')
add('States of wen\'s "D F2 B2 R" set (rules.py `dfbr`).', 'DFBR_COUNT', 'Nat', nat(DF.sum()))
L += ['end cardsref', 'end EOSwitch', '']
open(os.path.join(here, 'EOSwitch', 'CardsRef.lean'), 'w').write('\n'.join(L))
print('wrote EOSwitch/CardsRef.lean:', len(L), 'lines')
