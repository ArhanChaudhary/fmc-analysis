#!/usr/bin/env python3
"""Writes EOSwitch/Study.lean: output of the research, copied verbatim into Lean string literals, so that the
theorems `*_matches_study` compare what Lean computes with exactly what the research wrote.

    research/out/dist_hist.txt          eoswtools dist      (EO-kept DR distance histogram)
    research/out/variants_by_drm.tsv    src/step1.py        (per DRM: cosets, mean, plain <= 5/6/7, ...)
    research/out/SUMMARY.md             src/summary.py      (seven tables, each copied from its heading line to the
                                                             end of the table, unchanged)

Run from this directory:   python3 gen_study.py      (it must come out unchanged)"""
import os
here = os.path.dirname(os.path.abspath(__file__))
out_dir = os.path.join(here, '..', '..', 'research', 'out')
FILES = [('DIST_HIST_TXT', 'dist_hist.txt'), ('VARIANTS_BY_DRM_TSV', 'variants_by_drm.tsv')]
# (Lean name, start of the heading line in SUMMARY.md, which table after it: 0 = the first)
TABLES = [('SUM_PLAIN', '## 1. Exact distance and the free options (P1)'),
          ('SUM_4C4E_PAIRED', '**4c4e, one feature: bad U/D edges with a pair**'),
          ('SUM_4C4E_SLICE', '**4c4e, two features: paired edges, and whether the two bad edges are in one slice'),
          ('SUM_4C4E_BARS', '**4c4e: pairs split by the number of paired edges (bars)**'),
          ('SUM_4C2E_P2S', '**4c2e: 2 x (pairs + side pairs / 2)**'),
          ('SUM_7C8E_PAIRS', '**7c8e: pairs**'),
          ('SUM_2C2E', '**2c2e: a paired edge, JZP**')]

def block(lines, head):
    """The heading line, then everything up to the end of the first table after it."""
    i = next(k for k, l in enumerate(lines) if l.startswith(head))
    j = next(k for k in range(i + 1, len(lines)) if lines[k].startswith('|'))
    k = j
    while k < len(lines) and lines[k].startswith('|'): k += 1
    return '\n'.join([lines[i]] + lines[j:k]) + '\n'

lines = ['/-',
         '  EOSwitch.Study — GENERATED by `gen_study.py`, do not edit: output of the research, verbatim.',
         '  Only the theorems named `…_matches_study` read it.',
         '-/', '', 'namespace EOSwitch', 'namespace study', '']
for name, fn in FILES:
    txt = open(os.path.join(out_dir, fn)).read()
    assert '"#' not in txt
    lines += [f'/-- research/out/{fn}, verbatim. -/', f'def {name} : String := r#"{txt}"#', '']
summary = open(os.path.join(out_dir, 'SUMMARY.md')).read().split('\n')
for name, head in TABLES:
    txt = block(summary, head)
    assert '"#' not in txt
    lines += [f'/-- research/out/SUMMARY.md: the table under its line "{head[:60]}…", verbatim. -/',
              f'def {name} : String := r#"{txt}"#', '']
lines += ['end study', 'end EOSwitch', '']
open(os.path.join(here, 'EOSwitch', 'Study.lean'), 'w').write('\n'.join(lines))
print('wrote EOSwitch/Study.lean')
