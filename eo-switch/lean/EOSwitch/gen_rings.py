#!/usr/bin/env python3
"""Writes EOSwitch/RingsRef.lean: the exact integer cells of the two-ring tables, copied from the research's
`research/out/rings_lean_ref.json` (written by `research/src/xrings.py`) into Lean literals, so that no number of
RingsThm.lean is typed by hand.  A cell is [states, DR <= 5, DR <= 6, DR <= 7].

Run from this directory:   python3 gen_rings.py      (rerun after xrings.py; if a number changed, the build fails)"""
import os, json
here = os.path.dirname(os.path.abspath(__file__))
R = json.load(open(os.path.join(here, '..', '..', 'research', 'out', 'rings_lean_ref.json')))
DRMS = ['4c4e', '4c2e', '3c2e', '7c8e', '8c8e', '2c2e', '4c6e', '3c4e', '3c6e', '5c4e', '5c6e', '6c6e']

def nat(x):
    assert isinstance(x, int) and x >= 0, x
    return str(x)
def lst(l): return '[' + ', '.join(nat(x) for x in l) + ']'
def lst2(ll, ind='  '):
    if not ll: return '[]'
    return '[' + (',\n' + ind + ' ').join(lst(l) for l in ll) + ']'
def by_drm(d):
    assert list(d.keys()) == DRMS, list(d.keys())
    return '[' + ',\n   '.join(f"({k[0]}, {k[2]}, {lst2(v, '    ')})" for k, v in d.items()) + ']'
def s(x):
    assert all(c in '<>oE-' for c in x) and len(x) == 8, x
    return '"' + x + '"'

L = ['/-',
     '  EOSwitch.RingsRef — GENERATED by `gen_rings.py`, do not edit: the exact cells of the two-ring tables as the',
     '  research computed them (research/out/rings_lean_ref.json).  Only RingsThm.lean reads it: each theorem there',
     '  says that what Lean computes from its own definitions equals one of these tables.',
     '  A cell is [states, DR in ≤ 5, DR in ≤ 6 ("sub-7"), DR in ≤ 7].',
     '-/', '', 'namespace EOSwitch', 'namespace ringsref', '']
def add(doc, name, typ, body): L.extend([f'/-- {doc} -/', f'def {name} : {typ} :=', '  ' + body, ''])
add('States by side turns 0 … 5.', 'SIGMA_HIST', 'List Nat', lst(R['sigma_hist']))
add('The cell of each side-turn count 0 … 5 (all states).', 'SIGMA_CELLS', 'List (List Nat)', lst2(R['sigma_cells']))
add('4c4e: the cell of each count of half turns to two bars 0 … 5.', 'H_BANDS', 'List (List Nat)', lst2(R['h_bands']))
add('4c4e: [row swaps, slot type] ++ cell, for swaps 0 … 5 and slot type 0 … 2.', 'SWAPS_SLOT', 'List (List Nat)', lst2(R['swaps_slot']))
add('Ring pairs of 4c4e by row swaps 0 … 5.', 'RING_CLASSES_HIST', 'List Nat', lst(R['ring_classes_hist']))
add('4c4e: [pairs, half-turn group (0: ≤ 1, 1: 2, 2: 3, 3: ≥ 4)] ++ cell, the groups that occur.', 'PAIRS_H', 'List (List Nat)', lst2(R['pairs_h']))
add('4c4e: [group of the paired-edge card (0 both bad edges paired, 1 one paired and edge ARM 1, 2 the rest), '
    'half-turn group (0: ≤ 2, 1: 3, 2: ≥ 4)] ++ cell, the groups that occur.', 'CARD_SPLIT', 'List (List Nat)', lst2(R['card_split']))
add('4c4e with 3 half turns to two bars, by pairs 0 … 3.', 'INSIDE3_PAIRS', 'List (List Nat)', lst2(R['inside3']['pairs']))
add('The same by side pairs 0, 1, 2 or more.', 'INSIDE3_SIDE', 'List (List Nat)', lst2(R['inside3']['side']))
add('The same by edge ARM 1, edge ARM 0 or 2.', 'INSIDE3_EARM1', 'List (List Nat)', lst2(R['inside3']['earm1']))
add('The same by paired edges 0, 1, 2.', 'INSIDE3_EDGES_PAIRED', 'List (List Nat)', lst2(R['inside3']['edges_paired']))
add('3 pairs: [unpaired corner in the layer of the edge that lacks it, a bad piece in the two places behind it, '
    'both bad edges in one layer and opposite, row swaps, states, states with DR in ≤ 6].', 'THREE_RULE', 'List (List Nat)', lst2(R['three_rule']))
pat = R['patterns']
add('The ring pairs with at most 2 row swaps, up to exchanging the layers and mirroring: (one ring, the other ring, '
    '[row swaps, pairs, states, states with DR in ≤ 6]).  A ring is read clockwise from a corner: corner, edge, '
    "corner, edge, …; '>' a corner pointing clockwise, '<' counter-clockwise, 'o' a good corner, 'E' a bad edge "
    "place, '-' a good one.", 'PATTERNS', 'List (String × String × List Nat)',
    '[' + ',\n   '.join(f'({s(p[0])}, {s(p[1])}, {lst(p[2:])})' for p in pat) + ']')
add('[pairs, row swaps, number of ring pairs] over the 780 ring pairs of 4c4e.', 'PAIRS_SWAPS_CLASSES', 'List (List Nat)', lst2(R['pairs_swaps_classes']))
pc = sorted((int(k), v) for k, v in R['pair_change'].items())
add('(change in the number of pairs by one row swap, how often) over the 780 ring pairs × 16 row swaps.', 'PAIR_CHANGE', 'List (Int × Nat)',
    '[' + ', '.join(f'({k}, {nat(v)})' for k, v in pc) + ']')
add('Per DRM (c, e): [side turns] ++ cell, the counts that occur.', 'SIGMA_DRM', 'List (Nat × Nat × List (List Nat))', by_drm(R['sigma_drm']))
add('Per DRM (c, e): [quarter turns, half turns] ++ cell of the setups with the fewest side turns (fewest quarter '
    'turns among those), by side turns then quarter turns.', 'PROFILES', 'List (Nat × Nat × List (List Nat))', by_drm(R['profiles']))
add("Per DRM (c, e): [group of the DRM's card (first match wins), 0 short setup / 1 not] ++ cell, the groups that "
    'occur.  Short: at most 3 side turns with 1 quarter turn (4c4e) or 2 (the other DRMs).', 'CROSS', 'List (Nat × Nat × List (List Nat))', by_drm(R['cross']))
L += ['end ringsref', 'end EOSwitch', '']
open(os.path.join(here, 'EOSwitch', 'RingsRef.lean'), 'w').write('\n'.join(L))
print('wrote EOSwitch/RingsRef.lean:', len(pat), 'patterns,', sum(len(v) for v in R['profiles'].values()), 'profile rows')
