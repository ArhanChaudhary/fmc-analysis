#!/usr/bin/env python3
"""Write ImpliedEO/Sets.lean: the 691 sets of the study (research/out/study.json), each as its two or three EOs,
for Lean to check that they hold on the same scrambles."""
import json, re, os
HERE = os.path.dirname(os.path.abspath(__file__))
S = json.load(open(os.path.join(HERE, '..', '..', 'research', 'out', 'study.json')))
AXN = {'FB': '.fb', 'RL': '.rl', 'UD': '.ud'}
def mv(m): return m.replace("'", "'")
def eo(txt):
    body, ax = txt.rsplit(' on ', 1)
    if body == '(EO skip)': n, i = [], []
    else:
        m = re.match(r'^([^()]*?)\s*(?:\(([^()]*)\))?$', body)
        n, i = m.group(1).split(), (m.group(2) or '').split()
    return f"⟨{AXN[ax]}, [{', '.join(n)}], [{', '.join(i)}]⟩"
L = json.load(open(os.path.join(HERE, '..', '..', 'research', 'out', 'longer.json')))
PROBE = ['  [' + eo(r['X'] + ' on FB') + ', ' + eo(r['Y'] + ' on RL') + '],' for r in L['probe']]
PROBE[-1] = PROBE[-1].rstrip(',')
order = ['T1', 'T2', 'P1', 'P2', 'P3', 'P4', 'P5']
sets = sorted(S['sets'], key=lambda s: (order.index(s['type']), s['text']))
lines = ['/-', 'The 691 sets of scrambles with two or more EOs of at most 5 moves, as listed on the page (generated by',
         'gen_sets.py from the Python enumeration), and the check that the EOs of each set hold on the same scrambles.', '-/',
         'import ImpliedEO.Trick', 'namespace ImpliedEO', 'open Mv', '',
         'def allSets : List (List EO) := [']
lines += ['  [' + ', '.join(eo(t) for t in s['text']) + '],' for s in sets]
lines[-1] = lines[-1].rstrip(',')
lines += [']', '',
 '/-- Every EO of a set has the same two cases as the set\'s first EO. -/',
 'def setOk (l : List EO) : Bool :=',
 '  match l with',
 '  | [] => false',
 '  | X :: rest => rest.all fun Y => decide (X.same Y)',
 '',
 'theorem allSets_count : allSets.length = 691 ∧ (allSets.filter fun l => l.length == 3).length = 13 := by native_decide',
 'theorem allSets_ok : allSets.all setOk = true := by native_decide',
 'theorem allSets_short : allSets.all (fun l => l.all fun X => decide (X.len ≤ 5)) = true := by native_decide',
 '',
 '/-- **The list is right.**  In each of the 691 sets, every EO holds on exactly the scrambles the first one holds on. -/',
 'theorem allSets_equiv (l : List EO) (hl : l ∈ allSets) (X Y : EO) (hX : l.head? = some X) (hY : Y ∈ l.tail)',
 '    (scr : List Move) : X.holds scr ↔ Y.holds scr := by',
 '  have h := List.all_eq_true.mp allSets_ok l hl',
 '  cases l with',
 '  | nil => simp at hX',
 '  | cons Z rest =>',
 '    simp only [List.head?_cons, Option.some.injEq] at hX',
 '    subst hX',
 '    simp only [setOk] at h',
 '    exact EO.holds_of_same (of_decide_eq_true (List.all_eq_true.mp h Y hY)) scr',
 '',
 '/-- The 230 EOs R L (c), c an R/L case of at most 3 moves, each with its F/B partner F B (pattern). -/',
 'def probeSets : List (List EO) := ['] + PROBE + [']', '',
 'theorem probeSets_count : probeSets.length = 230 := by native_decide',
 'theorem probeSets_ok : probeSets.all setOk = true := by native_decide',
 '', 'end ImpliedEO', '']
open(os.path.join(HERE, 'ImpliedEO', 'Sets.lean'), 'w').write('\n'.join(lines))
print(len(sets), 'sets written')
