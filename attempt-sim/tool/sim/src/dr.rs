//! The domino-reduction (DR) group `<U, D, R2, L2, F2, B2>` as coordinates and move tables (the model of the
//! *Judging a DR* study).
//!
//! ```text
//!   corner positions : 0 UFR 1 UFL 2 UBL 3 UBR 4 DFR 5 DFL 6 DBL 7 DBR
//!   U/D-layer edges  : 0 UF 1 UL 2 UB 3 UR 4 DF 5 DL 6 DB 7 DR
//!   E-slice edges    : 0 FR 1 FL 2 BL 3 BR
//!   moves            : 0 U 1 U2 2 U' 3 D 4 D2 5 D' 6 R2 7 L2 8 F2 9 B2
//! ```
//!
//! In the DR group no piece is ever twisted or flipped, so a state is three permutations ("which piece sits at each
//! position"), stored as their lexicographic ranks: the coordinates `c` (0..40320), `e` (0..40320), `s` (0..24).  Only
//! states with `parity(c) ^ parity(e) == parity(s)` are reachable: 19,508,428,800 states.
//!
//! The 16 symmetries are the rotations and reflections of the cube that keep the U/D axis, generated by y, x2 and the
//! mirror L<->R; a symmetry acts on a state by conjugation.

/// Number of corner (and of U/D-edge) permutations, 8!.
pub const NC: usize = 40320;
pub const NE: usize = 40320;
/// Number of E-slice permutations, 4!.
pub const NS: usize = 24;
pub const NMOVES: usize = 10;
pub const NSYM: usize = 16;

pub const MOVE_NAMES: [&str; NMOVES] = ["U", "U2", "U'", "D", "D2", "D'", "R2", "L2", "F2", "B2"];
pub const MOVE_IS_QUARTER: [bool; NMOVES] = [true, false, true, true, false, true, false, false, false, false];
/// Face (U D R L F B = 0..5) of each DR move.
pub const MOVE_FACE: [u8; NMOVES] = [0, 0, 0, 1, 1, 1, 2, 3, 4, 5];
/// The DR moves as face turns of the whole cube (move numbers of [`crate::cube::Move`]).
pub const AS_CUBE_MOVE: [u8; NMOVES] = [0, 1, 2, 3, 4, 5, 7, 10, 13, 16];
/// The half turns U2 D2 R2 L2 F2 B2.
pub const HALF_MOVES: [usize; 6] = [1, 4, 6, 7, 8, 9];

/// A position map: whatever sits at position `p` goes to position `c[p]` (and `e`, `s` for the edges).
struct PosMap {
    c: [u8; 8],
    e: [u8; 8],
    s: [u8; 4],
}

// U clockwise seen from above: UFR->UFL->UBL->UBR
const MAP_U: PosMap = PosMap { c: [1, 2, 3, 0, 4, 5, 6, 7], e: [1, 2, 3, 0, 4, 5, 6, 7], s: [0, 1, 2, 3] };
// D clockwise seen from below: DFL->DFR->DBR->DBL
const MAP_D: PosMap = PosMap { c: [0, 1, 2, 3, 7, 4, 5, 6], e: [0, 1, 2, 3, 7, 4, 5, 6], s: [0, 1, 2, 3] };
const MAP_R2: PosMap = PosMap { c: [7, 1, 2, 4, 3, 5, 6, 0], e: [0, 1, 2, 7, 4, 5, 6, 3], s: [3, 1, 2, 0] };
const MAP_L2: PosMap = PosMap { c: [0, 6, 5, 3, 4, 2, 1, 7], e: [0, 5, 2, 3, 4, 1, 6, 7], s: [0, 2, 1, 3] };
const MAP_F2: PosMap = PosMap { c: [5, 4, 2, 3, 1, 0, 6, 7], e: [4, 1, 2, 3, 0, 5, 6, 7], s: [1, 0, 2, 3] };
const MAP_B2: PosMap = PosMap { c: [0, 1, 7, 6, 4, 5, 3, 2], e: [0, 1, 6, 3, 4, 5, 2, 7], s: [0, 1, 3, 2] };
// the symmetry generators y, x2 and the mirror L<->R
const SYM_Y: PosMap = PosMap { c: [1, 2, 3, 0, 5, 6, 7, 4], e: [1, 2, 3, 0, 5, 6, 7, 4], s: [1, 2, 3, 0] };
const SYM_X2: PosMap = PosMap { c: [7, 6, 5, 4, 3, 2, 1, 0], e: [6, 5, 4, 7, 2, 1, 0, 3], s: [3, 2, 1, 0] };
const SYM_M: PosMap = PosMap { c: [1, 0, 3, 2, 5, 4, 7, 6], e: [0, 3, 2, 1, 4, 7, 6, 5], s: [1, 0, 3, 2] };

/// A DR state: the piece at each position.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct St {
    pub c: [u8; 8],
    pub e: [u8; 8],
    pub s: [u8; 4],
}

impl St {
    pub const ID: St = St { c: [0, 1, 2, 3, 4, 5, 6, 7], e: [0, 1, 2, 3, 4, 5, 6, 7], s: [0, 1, 2, 3] };

    fn apply_map(self, t: &PosMap) -> St {
        let mut r = St::ID;
        for p in 0..8 {
            r.c[t.c[p] as usize] = self.c[p];
            r.e[t.e[p] as usize] = self.e[p];
        }
        for p in 0..4 {
            r.s[t.s[p] as usize] = self.s[p];
        }
        r
    }

    pub fn apply_move(self, m: usize) -> St {
        match m {
            0 => self.apply_map(&MAP_U),
            1 => self.apply_move(0).apply_move(0),
            2 => self.apply_move(1).apply_move(0),
            3 => self.apply_map(&MAP_D),
            4 => self.apply_move(3).apply_move(3),
            5 => self.apply_move(4).apply_move(3),
            6 => self.apply_map(&MAP_R2),
            7 => self.apply_map(&MAP_L2),
            8 => self.apply_map(&MAP_F2),
            _ => self.apply_map(&MAP_B2),
        }
    }

    /// `state(A then B)`, with `self` = state(A) and `b` = state(B).
    pub fn then(self, b: St) -> St {
        St {
            c: std::array::from_fn(|p| self.c[b.c[p] as usize]),
            e: std::array::from_fn(|p| self.e[b.e[p] as usize]),
            s: std::array::from_fn(|p| self.s[b.s[p] as usize]),
        }
    }

    pub fn inv(self) -> St {
        let mut r = St::ID;
        for p in 0..8 {
            r.c[self.c[p] as usize] = p as u8;
            r.e[self.e[p] as usize] = p as u8;
        }
        for p in 0..4 {
            r.s[self.s[p] as usize] = p as u8;
        }
        r
    }

    pub fn unrank(c: usize, e: usize, s: usize) -> St {
        St { c: unrank_perm(c), e: unrank_perm(e), s: unrank_perm(s) }
    }
}

const FACT: [usize; 9] = [1, 1, 2, 6, 24, 120, 720, 5040, 40320];

/// Lexicographic rank of a permutation of `0..p.len()`.
pub fn rank_perm(p: &[u8]) -> usize {
    let n = p.len();
    (0..n).map(|i| p[i + 1..].iter().filter(|&&x| x < p[i]).count() * FACT[n - 1 - i]).sum()
}

/// The permutation of `0..N` with lexicographic rank `r`.
pub fn unrank_perm<const N: usize>(mut r: usize) -> [u8; N] {
    let mut p = [0u8; N];
    let mut used = [false; 8];
    for (i, slot) in p.iter_mut().enumerate() {
        let mut k = r / FACT[N - 1 - i];
        r %= FACT[N - 1 - i];
        let mut j = 0;
        loop {
            if !used[j] {
                if k == 0 {
                    break;
                }
                k -= 1;
            }
            j += 1;
        }
        *slot = j as u8;
        used[j] = true;
    }
    p
}

/// 0 for an even permutation, 1 for an odd one.
pub fn perm_parity(p: &[u8]) -> u8 {
    let mut parity = 0;
    let mut seen = [false; 8];
    for i in 0..p.len() {
        let mut j = i;
        let mut len = 0usize;
        while !seen[j] {
            seen[j] = true;
            j = p[j] as usize;
            len += 1;
        }
        if len > 0 && len.is_multiple_of(2) {
            parity ^= 1;
        }
    }
    parity
}

/// A DR state as coordinates.
pub type DrState = (usize, usize, usize);
pub const SOLVED: DrState = (0, 0, 0);

/// Move, symmetry, inverse and parity tables on the coordinates.
pub struct DrTables {
    /// `cmove[m][c]`: corner coordinate after move m (likewise edges and slice)
    pub cmove: Vec<[u16; NC]>,
    pub emove: Vec<[u16; NE]>,
    pub smove: [[u8; NS]; NMOVES],
    /// `csym[S][c]`: corner coordinate of the conjugate by symmetry S (likewise edges and slice)
    pub csym: Vec<[u16; NC]>,
    pub esym: Vec<[u16; NE]>,
    pub ssym: [[u8; NS]; NSYM],
    /// coordinates of the inverse permutation
    pub cinv: Vec<u16>,
    pub einv: Vec<u16>,
    pub sinv: [u8; NS],
    pub cpar: Vec<u8>,
    pub epar: Vec<u8>,
    pub spar: [u8; NS],
    /// the inverse of each symmetry
    pub sym_inv: [usize; NSYM],
}

/// Position maps of the 16 symmetries, index `mirror * 8 + x2 * 4 + y power`.
fn symmetry_maps() -> [([u8; 8], [u8; 8], [u8; 4]); NSYM] {
    std::array::from_fn(|sym| {
        let mut c: [u8; 8] = std::array::from_fn(|p| p as u8);
        let mut e = c;
        let mut s: [u8; 4] = std::array::from_fn(|p| p as u8);
        let mut then = |g: &PosMap| {
            for p in 0..8 {
                c[p] = g.c[c[p] as usize];
                e[p] = g.e[e[p] as usize];
            }
            for p in 0..4 {
                s[p] = g.s[s[p] as usize];
            }
        };
        if sym & 8 != 0 {
            then(&SYM_M);
        }
        if sym & 4 != 0 {
            then(&SYM_X2);
        }
        for _ in 0..(sym & 3) {
            then(&SYM_Y);
        }
        (c, e, s)
    })
}

/// The conjugate of a state by a symmetry given as position maps: the state seen after turning (or mirroring) the cube.
fn conj(a: St, map: &([u8; 8], [u8; 8], [u8; 4])) -> St {
    let (sc, se, ss) = map;
    let mut r = St::ID;
    for p in 0..8 {
        r.c[sc[p] as usize] = sc[a.c[p] as usize];
        r.e[se[p] as usize] = se[a.e[p] as usize];
    }
    for p in 0..4 {
        r.s[ss[p] as usize] = ss[a.s[p] as usize];
    }
    r
}

impl DrTables {
    pub fn new() -> DrTables {
        let syms = symmetry_maps();
        let mut t = DrTables {
            cmove: vec![[0; NC]; NMOVES],
            emove: vec![[0; NE]; NMOVES],
            smove: [[0; NS]; NMOVES],
            csym: vec![[0; NC]; NSYM],
            esym: vec![[0; NE]; NSYM],
            ssym: [[0; NS]; NSYM],
            cinv: vec![0; NC],
            einv: vec![0; NE],
            sinv: [0; NS],
            cpar: vec![0; NC],
            epar: vec![0; NE],
            spar: [0; NS],
            sym_inv: [0; NSYM],
        };
        // corners and U/D edges are numbered the same way, so one loop fills both
        for x in 0..NC {
            let a = St::unrank(x, x, 0);
            t.cpar[x] = perm_parity(&a.c);
            t.epar[x] = t.cpar[x];
            t.cinv[x] = rank_perm(&a.inv().c) as u16;
            t.einv[x] = t.cinv[x];
            for m in 0..NMOVES {
                let b = a.apply_move(m);
                t.cmove[m][x] = rank_perm(&b.c) as u16;
                t.emove[m][x] = rank_perm(&b.e) as u16;
            }
            for (sym, map) in syms.iter().enumerate() {
                let b = conj(a, map);
                t.csym[sym][x] = rank_perm(&b.c) as u16;
                t.esym[sym][x] = rank_perm(&b.e) as u16;
            }
        }
        for s in 0..NS {
            let a = St::unrank(0, 0, s);
            t.spar[s] = perm_parity(&a.s);
            t.sinv[s] = rank_perm(&a.inv().s) as u8;
            for m in 0..NMOVES {
                t.smove[m][s] = rank_perm(&a.apply_move(m).s) as u8;
            }
            for (sym, map) in syms.iter().enumerate() {
                t.ssym[sym][s] = rank_perm(&conj(a, map).s) as u8;
            }
        }
        for sym in 0..NSYM {
            for other in 0..NSYM {
                // first `sym`, then `other`: the identity iff `other` is the inverse
                let c: [u8; 8] = std::array::from_fn(|p| syms[other].0[syms[sym].0[p] as usize]);
                let e: [u8; 8] = std::array::from_fn(|p| syms[other].1[syms[sym].1[p] as usize]);
                if c == St::ID.c && e == St::ID.e {
                    t.sym_inv[sym] = other;
                }
            }
        }
        t
    }

    #[inline]
    pub fn apply(&self, m: usize, st: DrState) -> DrState {
        (self.cmove[m][st.0] as usize, self.emove[m][st.1] as usize, self.smove[m][st.2] as usize)
    }

    pub fn inverse(&self, st: DrState) -> DrState {
        (self.cinv[st.0] as usize, self.einv[st.1] as usize, self.sinv[st.2] as usize)
    }

    /// The smallest coordinates among the 16 symmetric copies of a state: a name for it that does not depend on which
    /// of the rotations about the DR axis it is looked at from.
    pub fn canonical(&self, st: DrState) -> DrState {
        (0..NSYM)
            .map(|sym| (self.csym[sym][st.0] as usize, self.esym[sym][st.1] as usize, self.ssym[sym][st.2] as usize))
            .min()
            .unwrap()
    }
}

impl Default for DrTables {
    fn default() -> Self {
        Self::new()
    }
}

/// The search's canonical DR-move sequences: never the same face twice in a row, never three turns in a row on one
/// axis (so `U D` and `D U` are both kept, `U D U` is not).  `last_face` is the face of the last move (`NONE` at the
/// start), `axis_run` the axis of the last two moves if both were on one axis (`NONE` otherwise).
#[derive(Clone, Copy)]
pub struct DrCanon {
    pub last_face: u8,
    pub axis_run: u8,
}

const NONE: u8 = 0xFF;

impl DrCanon {
    pub const START: DrCanon = DrCanon { last_face: NONE, axis_run: NONE };

    #[inline]
    pub fn allows(self, m: usize) -> bool {
        let f = MOVE_FACE[m];
        f != self.last_face && f / 2 != self.axis_run
    }

    #[inline]
    pub fn after(self, m: usize) -> DrCanon {
        let f = MOVE_FACE[m];
        let axis_run = if self.last_face != NONE && self.last_face / 2 == f / 2 { f / 2 } else { NONE };
        DrCanon { last_face: f, axis_run }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rank_and_unrank_are_inverse() {
        for r in (0..NC).step_by(97) {
            assert_eq!(rank_perm(&unrank_perm::<8>(r)), r);
        }
        for r in 0..NS {
            assert_eq!(rank_perm(&unrank_perm::<4>(r)), r);
        }
    }

    #[test]
    fn moves_have_the_right_order() {
        for m in 0..NMOVES {
            let order = if MOVE_IS_QUARTER[m] { 4 } else { 2 };
            let mut a = St::ID;
            for k in 1..=order {
                a = a.apply_move(m);
                assert_eq!(a == St::ID, k == order);
            }
        }
    }

    #[test]
    fn symmetries_have_inverses() {
        let t = DrTables::new();
        for sym in 0..NSYM {
            let back = t.sym_inv[sym];
            for c in (0..NC).step_by(101) {
                assert_eq!(t.csym[back][t.csym[sym][c] as usize] as usize, c);
            }
        }
    }
}

#[cfg(test)]
mod cube_agreement {
    use super::*;
    use crate::cube::{Move, MoveTables};

    /// The whole-cube model and the DR model agree on every DR move (they number places the same way).
    #[test]
    fn dr_moves_match_the_cube() {
        let t = MoveTables::new();
        let mut cube = crate::cube::Cube::SOLVED;
        let mut st = St::ID;
        let mut x = 12345u64;
        for _ in 0..500 {
            x = crate::rng::mix(x);
            let m = (x % NMOVES as u64) as usize;
            cube = t.turn(&cube, Move(AS_CUBE_MOVE[m]));
            st = st.apply_move(m);
            let (c, e, s) = cube.dr_perms().expect("still a DR");
            assert_eq!((c, e, s), (st.c, st.e, st.s));
        }
    }
}
