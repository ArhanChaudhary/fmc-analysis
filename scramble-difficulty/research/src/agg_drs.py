#!/usr/bin/env python3
"""Per-scramble numbers from the DR lists of enum_all.py, for DRs of at most 10 and of at most 11 moves.

usage: agg_drs.py PARTS_DIR OUT_DIR [workers]
For each population (first letter of the scramble id: u uniform, r official, g generated by the clock, p generated
current solver, o generated old solver) and each cap in (10, 11), OUT_DIR gets
  tgt<cap>_<pop>.tsv        id n8 n9 n10 n11 best n_near good19 good20 good21 good22 gsub bestdr
  tgt<cap>_<pop>_axis.tsv   id axis + the same, for the DRs on that DR axis
  tot<cap>_<pop>.tsv        id t14 .. t30 : DRs by DR length + optimal finish (14 = 14 or less, 30 = 30 or more)
  drqt<cap>_<pop>.tsv       id h0 .. h5 : DRs by the last digit of their corner case
  eoaxis<cap>_<pop>.tsv     id dr_<eo>_<dr> for the six pairs: DR states on DR axis <dr> listed through an EO on <eo>
n8..n11 count DRs of at most k moves among those of at most cap; best = min of DR length + optimal finish (99: none);
n_near = DRs within one move of best; good<T> = DRs with DR + finish <= T; gsub = DRs in corner case 0c0, 2c3, 4a1 or
4b2 with at most 4 bad edges; bestdr = shortest DR.  A scramble with no DR of at most cap has no row in tgt files
(as in the earlier files) but is listed in ids_<pop>.txt."""
import sys, os, gzip, glob, multiprocessing
from collections import defaultdict

GOODC = {'0c0', '2c3', '4a1', '4b2'}
TS = (19, 20, 21, 22)
POP = {'u': 'uni', 'r': 'real', 'g': 'gen', 'p': 'pnew', 'o': 'pold', 'w': 'wit'}
AXES = ['UD', 'FB', 'RL']
PAIRS = [(e, a) for e in AXES for a in AXES if a != e]
KEYS = ['n8', 'n9', 'n10', 'n11', 'best', 'n_near'] + ['good%d' % t for t in TS] + ['gsub', 'bestdr']

def new():
    return {'n8': 0, 'n9': 0, 'n10': 0, 'n11': 0, 'best': 99, 'bestdr': 99, 'gsub': 0, 'tots': [], 'good19': 0, 'good20': 0, 'good21': 0, 'good22': 0}
def add(A, L, tot, good):
    for k in (8, 9, 10, 11):
        if L <= k: A['n%d' % k] += 1
    if tot < A['best']: A['best'] = tot
    if L < A['bestdr']: A['bestdr'] = L
    for t in TS:
        if tot <= t: A['good%d' % t] += 1
    if good: A['gsub'] += 1
    A['tots'].append(tot)
def fin(A):
    b = A['best']; A['n_near'] = sum(1 for t in A['tots'] if t <= b + 1)
    return [A[k] for k in KEYS]

def part(path):
    out = {}
    cur = None; rows = []
    def close(k, rows):
        res = {}
        for cap in (10, 11):
            S = new(); X = {}; H = [0] * 6; T = [0] * 17; E = dict.fromkeys(PAIRS, 0)
            for ax, L, via, sub, d in rows:
                for j, e in enumerate(AXES):
                    if e != ax and via[j] <= cap: E[(e, ax)] += 1
                if L > cap: continue
                cc, be = sub.split(); good = cc in GOODC and int(be[:-1]) <= 4; tot = L + d
                add(S, L, tot, good)
                if ax not in X: X[ax] = new()
                add(X[ax], L, tot, good)
                H[int(cc[-1])] += 1; T[min(max(tot, 14), 30) - 14] += 1
            res[cap] = (fin(S) if S['tots'] else None, {a: fin(v) for a, v in X.items()}, H, T, [E[p] for p in PAIRS])
        out[k] = res
    for line in gzip.open(path, 'rt'):
        r = line.rstrip('\n').split('\t')
        if r[0] != cur:
            if cur is not None: close(cur, rows)
            cur = r[0]; rows = []
        rows.append((r[1].replace('/', ''), int(r[3]), (int(r[5]), int(r[6]), int(r[7])), r[8], int(r[9])))
    if cur is not None: close(cur, rows)
    ids = open(path.replace('part_', 'done_').replace('.tsv.gz', '.txt')).read().split()
    return ids, out

def main():
    src, dst = sys.argv[1], sys.argv[2]; W = int(sys.argv[3]) if len(sys.argv) > 3 else 4
    os.makedirs(dst, exist_ok=True)
    parts = sorted(glob.glob(os.path.join(src, 'part_*.tsv.gz')))
    ids_all = defaultdict(list); res = {}
    with multiprocessing.Pool(W) as pool:
        for ids, out in pool.imap(part, parts):
            for k in ids: ids_all[POP[k[0]]].append(k)
            res.update(out)
    def num(k): return int(k[1:])
    for pop, ids in ids_all.items():
        ids.sort(key=num)
        assert len(ids) == len(set(ids)), pop
        open(os.path.join(dst, 'ids_%s.txt' % pop), 'w').write('\n'.join(ids) + '\n')
        for cap in (10, 11):
            f1 = open(os.path.join(dst, 'tgt%d_%s.tsv' % (cap, pop)), 'w'); f1.write('id\t' + '\t'.join(KEYS) + '\n')
            f2 = open(os.path.join(dst, 'tgt%d_%s_axis.tsv' % (cap, pop)), 'w'); f2.write('id\taxis\t' + '\t'.join(KEYS) + '\n')
            f3 = open(os.path.join(dst, 'tot%d_%s.tsv' % (cap, pop)), 'w'); f3.write('id\t' + '\t'.join('t%d' % t for t in range(14, 31)) + '\n')
            f4 = open(os.path.join(dst, 'drqt%d_%s.tsv' % (cap, pop)), 'w'); f4.write('id\t' + '\t'.join('h%d' % q for q in range(6)) + '\n')
            f5 = open(os.path.join(dst, 'eoaxis%d_%s.tsv' % (cap, pop)), 'w'); f5.write('id\t' + '\t'.join('dr_%s_%s' % p for p in PAIRS) + '\n')
            for k in ids:
                r = res.get(k)
                if r is None:
                    f5.write(k + '\t' + '\t'.join(['0'] * 6) + '\n'); continue
                S, X, H, T, E = r[cap]
                f5.write(k + '\t' + '\t'.join(map(str, E)) + '\n')
                if S is None: continue
                f1.write(k + '\t' + '\t'.join(map(str, S)) + '\n')
                for a in AXES:
                    if a in X: f2.write(k + '\t' + a + '\t' + '\t'.join(map(str, X[a])) + '\n')
                f3.write(k + '\t' + '\t'.join(map(str, T)) + '\n')
                f4.write(k + '\t' + '\t'.join(map(str, H)) + '\n')
            for f in (f1, f2, f3, f4, f5): f.close()
        print(pop, len(ids), 'scrambles')

if __name__ == '__main__':
    main()
