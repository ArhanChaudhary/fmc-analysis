#!/usr/bin/env python3
"""Writes HTRRoutes/Study.lean: output files of the research, copied verbatim into Lean string literals, so that the
theorems `*_matches_study` compare what Lean computes with exactly what the research wrote.

    research/out/checks/htr_states.tsv  htrtools dist     (the 663,552 HTR states: optimal finish, DR moves / half turns)
    research/out/checks/htr48.tsv       htrtools dist     (shortest linear DR -> HTR per 48-subset, over the HTR cosets)
    research/out/q9_alpha.tsv           bounding2.py      (FakeMMAP's alpha_i per corner path, from `htrtools alpha`)
    research/out/name_map.tsv           map_names.py      (the subset of each example scramble of docs 15 and 66)
    research/out/claims.tsv             claims.py         (only the rows C07, C08, C10)

Run from this directory:   python3 gen_study.py      (it must come out unchanged)"""
import os
here = os.path.dirname(os.path.abspath(__file__))
out_dir = os.path.join(here, '..', '..', 'research', 'out')
FILES = [('HTR_STATES_TSV', 'checks/htr_states.tsv'), ('HTR48_TSV', 'checks/htr48.tsv'),
         ('Q9_ALPHA_TSV', 'q9_alpha.tsv'), ('NAME_MAP_TSV', 'name_map.tsv')]
lines = ['/-',
         '  HTRRoutes.Study — GENERATED by `gen_study.py`, do not edit: output files of the research, verbatim.',
         '  Only the theorems named `…_matches_study` and `…_as_study` read them.',
         '-/', '', 'namespace HTRRoutes', 'namespace study', '']
for name, fn in FILES:
    txt = open(os.path.join(out_dir, fn)).read()
    assert '"#' not in txt
    lines += [f'/-- research/out/{fn}, verbatim. -/', f'def {name} : String := r#"{txt}"#', '']
claims = [l for l in open(os.path.join(out_dir, 'claims.tsv')).read().split('\n') if l.split('\t')[0] in ('C07', 'C08', 'C10')]
assert len(claims) == 3
for l in claims:
    assert '"#' not in l
    cid = l.split('\t')[0]
    lines += [f'/-- research/out/claims.tsv, row {cid}, verbatim. -/', f'def CLAIM_{cid} : String := r#"{l}"#', '']
lines += ['end study', 'end HTRRoutes', '']
open(os.path.join(here, 'HTRRoutes', 'Study.lean'), 'w').write('\n'.join(lines))
print('wrote HTRRoutes/Study.lean')
