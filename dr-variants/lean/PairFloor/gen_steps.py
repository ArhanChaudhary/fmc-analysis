#!/usr/bin/env python3
"""Writes PairFloor/Steps.lean: for each of the ten DR moves, what happens to the 16 corner/edge slots.
Read off the move tables of DRBound.Cube (srcC, srcE); Lean checks every line."""
SLOTS = [(0,0),(0,3),(1,0),(1,1),(2,1),(2,2),(3,2),(3,3),(4,4),(4,7),(5,4),(5,5),(6,5),(6,6),(7,6),(7,7)]
SRCC = {'U':[3,0,1,2,4,5,6,7],'U2':[2,3,0,1,4,5,6,7],"U'":[1,2,3,0,4,5,6,7],'D':[0,1,2,3,5,6,7,4],'D2':[0,1,2,3,6,7,4,5],"D'":[0,1,2,3,7,4,5,6],
        'R2':[7,1,2,4,3,5,6,0],'L2':[0,6,5,3,4,2,1,7],'F2':[5,4,2,3,1,0,6,7],'B2':[0,1,7,6,4,5,3,2]}
SRCE = {'U':[3,0,1,2,4,5,6,7],'U2':[2,3,0,1,4,5,6,7],"U'":[1,2,3,0,4,5,6,7],'D':[0,1,2,3,5,6,7,4],'D2':[0,1,2,3,6,7,4,5],"D'":[0,1,2,3,7,4,5,6],
        'R2':[0,1,2,7,4,5,6,3],'L2':[0,5,2,3,4,1,6,7],'F2':[4,1,2,3,0,5,6,7],'B2':[0,1,6,3,4,5,2,7]}
LEAN = {'U':'U','U2':'U2',"U'":"U'",'D':'D','D2':'D2',"D'":"D'",'R2':'R2','L2':'L2','F2':'F2','B2':'B2'}
NAME = {'U':'U','U2':'U2',"U'":'U3','D':'D','D2':'D2',"D'":'D3','R2':'R2','L2':'L2','F2':'F2','B2':'B2'}
out = ['/-', '  PairFloor.Steps — generated by gen_steps.py; do not edit.', '  One move at a time: which of the 16 slots are carried as a whole (the pair, if any, survives) and which',
       '  are split (at most 4, and only by a side half turn).', '-/', 'import PairFloor.Pairs', '', 'namespace DRBound', '']
def term(p, q, cp, eq): return f'ind (truePair {p} {q} (cf {cp}) (ef {eq}))'
for mv in SRCC:
    sc, se, nm = SRCC[mv], SRCE[mv], NAME[mv]
    rigid, broken = [], []
    for (p, q) in SLOTS:
        src = (sc[p], se[q])
        if src == (p, q): continue
        (rigid if src in SLOTS else broken).append(((p, q), src))
    side = mv in ('R2', 'L2', 'F2', 'B2')
    assert len(broken) == (4 if side else 0), (mv, broken)
    lhs = ' +\n      '.join(term(p, q, sc[p], se[q]) for (p, q) in SLOTS)
    out.append(f'/-- What `{mv}` does to the pieces at the 16 slots. -/')
    out.append(f'theorem moved_{nm} (cf ef : Fin 8 → Fin 8) :\n    pairsF (fun p => cf (Move.{LEAN[mv]}.srcC.get p)) (fun q => ef (Move.{LEAN[mv]}.srcE.get q)) =\n      {lhs} := rfl\n')
    conj = ' ∧\n    '.join(f'truePair {p} {q} c e = truePair {a} {b} c e' for ((p, q), (a, b)) in rigid)
    out.append(f'/-- `{mv}` carries these slots as a whole: a pair there before is a pair after. -/')
    out.append(f'theorem carried_{nm} : ∀ c e : Fin 8,\n    {conj} := by decide\n')
    # rewrite list: slot (p,q) receives pieces from slot (a,b): truePair p q (cf a) (ef b) -> truePair a b (cf a) (ef b)
    n = len(rigid)
    def proj(i):
        s = f'(carried_{nm} (cf {rigid[i][1][0]}) (ef {rigid[i][1][1]}))'
        if n == 1: return s
        return s + ''.join('.2' for _ in range(i)) + ('.1' if i < n - 1 else '')
    rws = ', '.join(proj(i) for i in range(n))
    if side:
        bl = '\n  '.join(f'have := ind_le (truePair {p} {q} (cf {a}) (ef {b}))' for ((p, q), (a, b)) in broken)
        br = '\n  '.join(f'have := ind_le (truePair {p} {q} (cf {p}) (ef {q}))' for ((p, q), _) in broken)
        out.append(f'/-- `{mv}` splits four slots and carries the rest: the number of true pairs moves by at most 4. -/')
        out.append(f'theorem step_{nm} (cf ef : Fin 8 → Fin 8) :\n    pairsF (fun p => cf (Move.{LEAN[mv]}.srcC.get p)) (fun q => ef (Move.{LEAN[mv]}.srcE.get q)) ≤ pairsF cf ef + 4 ∧\n    pairsF cf ef ≤ pairsF (fun p => cf (Move.{LEAN[mv]}.srcC.get p)) (fun q => ef (Move.{LEAN[mv]}.srcE.get q)) + 4 := by\n  rw [moved_{nm}]\n  simp only [pairsF, {rws}]\n  {bl}\n  {br}\n  omega\n')
    else:
        out.append(f'/-- `{mv}` carries every slot it touches: the number of true pairs does not change. -/')
        out.append(f'theorem step_{nm} (cf ef : Fin 8 → Fin 8) :\n    pairsF (fun p => cf (Move.{LEAN[mv]}.srcC.get p)) (fun q => ef (Move.{LEAN[mv]}.srcE.get q)) = pairsF cf ef := by\n  rw [moved_{nm}]\n  simp only [pairsF, {rws}]\n  omega\n')
out.append('end DRBound')
open('PairFloor/Steps.lean', 'w').write('\n'.join(out) + '\n')
print('written', len(out), 'blocks')
