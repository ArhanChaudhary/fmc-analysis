//! (L; P, S, T, N) of every HTR, read against the HTR's own corner skeleton.
//!
//! Advanced DR Bounding (Rodney Kinney, version of 23 Nov 2026): "A corner skeleton is any algorithm that solves
//! corners, modulo corner swaps and rotations.  L is the skeleton's move count after removing any corner swaps.  A
//! variant is any solution that can be obtained by inserting slices, corner swaps (X2 Y2 X2) and pure edge
//! permutations into the skeleton."
//!
//! Made exact here, section by section.  A solution is `h0 q1 h1 q2 ... qn hn`: quarter turns q, half-turn
//! sections h.  Inserting a slice or a corner swap of the side axes multiplies the corners by a symmetry of the cube
//! that keeps the U/D axis and both tetrads (8 of them: the three half-turn rotations and the identity, each with or
//! without the mirror that swaps R and F) and turns the rest of the solution into its mirror image; a pure edge
//! permutation does nothing to the corners; and a U2 or D2 next to a quarter turn only turns that quarter turn the
//! other way.  So the corner skeleton of a section with corner action g is the shortest half-turn sequence k with
//!
//!     k = u1 * gamma(g) * u2 * p     u1, u2 in {1, U2, D2},  gamma one of the 16 symmetries of the U/D axis,
//!                                    p one of the 8 above
//!
//! where u1 is only there after a quarter turn and u2 only before one.  `ell` = that length; the section's extra
//! moves = its length - ell.  L = quarter turns + the sum of ell; P, S, T, N are the extra moves of the sections
//! before the state with 2 quarter turns left, of the setup section, of the trigger section and of the finish.
//! Reading the inverse solution reverses the sections and each ell with them (`Sec::new` checks ell_first(g) =
//! ell_last(g^-1) and ell_mid(g) = ell_mid(g^-1)), so (P, S, T, N) of a 3qt skeleton becomes (N, T, S, P).
//!
//! Two checks of the reading run with the data (`run`): L never undercuts the shortest corner path of the HTR's
//! (quarter turns, corner kind) family, and on a sample of DRs it equals the shortest corner-only path through the
//! same corner cases at each quarter turn (`dp_len`).
use crate::core::{rank_perm, St};
use crate::meta::{goal_of, htr_like, qt_count, Cls, Ctx, Uni};
use crate::model::*;
use std::collections::HashMap;

fn corners(s: &St) -> St {
    St { c: s.c, e: St::ID.e, s: St::ID.s }
}

pub struct Sec {
    /// class of every corner state under turns of U and D and the 16 symmetries: "the corner case at a quarter turn"
    pub bcls: Vec<u16>,
    pub nb: usize,
    /// `ell[pos][corner rank of g]`, pos 0 first section, 1 middle, 2 last; 255 = not a half-turn corner state
    pub ell: [Vec<u8>; 3],
    /// corner ranks of the 8 symmetries a skeleton may end on
    pub solved: Vec<bool>,
}

impl Sec {
    pub fn new() -> Sec {
        // the 16 symmetries of the U/D axis, as corner permutations: generated by y (= U D'), x2 (= R2 L2) and
        // the mirror that swaps R and F (= R2 F2 R2 on corners)
        let gens = [corners(&word(&[0, 5])), corners(&word(&[6, 7])), corners(&word(&[6, 8, 6]))];
        let mut syms = vec![St::ID];
        let mut i = 0;
        while i < syms.len() {
            for g in &gens {
                let t = syms[i].mul(*g);
                if !syms.iter().any(|s| s.c == t.c) {
                    syms.push(t);
                }
            }
            i += 1;
        }
        assert_eq!(syms.len(), 16, "symmetries of the U/D axis");
        // half-turn length of the 96 corner states of HTR
        let mut hd: HashMap<usize, u8> = HashMap::new();
        let mut list = vec![St::ID];
        hd.insert(rank_perm(&St::ID.c), 0);
        let mut i = 0;
        while i < list.len() {
            let d = hd[&rank_perm(&list[i].c)];
            for &h in &HALF {
                let t = corners(&list[i].apply_move(h));
                if let std::collections::hash_map::Entry::Vacant(e) = hd.entry(rank_perm(&t.c)) {
                    e.insert(d + 1);
                    list.push(t);
                }
            }
            i += 1;
        }
        assert_eq!(list.len(), 96);
        let sym8: Vec<St> = syms.iter().copied().filter(|s| hd.contains_key(&rank_perm(&s.c))).collect();
        assert_eq!(sym8.len(), 8, "symmetries that keep the tetrads");
        let us = [St::ID, corners(&word(&[1])), corners(&word(&[4]))];
        let mut ell = [vec![255u8; 40320], vec![255u8; 40320], vec![255u8; 40320]];
        for g in &list {
            for (pos, table) in ell.iter_mut().enumerate() {
                let left: &[St] = if pos == 0 { &us[..1] } else { &us };
                let right: &[St] = if pos == 2 { &us[..1] } else { &us };
                let mut best = 255u8;
                for sy in &syms {
                    let cg = sy.inv().mul(*g).mul(*sy);
                    for u1 in left {
                        for u2 in right {
                            for p in &sym8 {
                                let k = u1.mul(cg).mul(*u2).mul(*p);
                                best = best.min(hd[&rank_perm(&k.c)]);
                            }
                        }
                    }
                }
                table[rank_perm(&g.c)] = best;
            }
        }
        // reading the inverse reverses the sections
        for g in &list {
            let (r, ri) = (rank_perm(&g.c), rank_perm(&g.inv().c));
            assert_eq!(ell[0][r], ell[2][ri], "first section of a solution = last section of its inverse");
            assert_eq!(ell[1][r], ell[1][ri]);
        }
        // corner cases at a quarter turn
        let mut bcls = vec![u16::MAX; 40320];
        let mut nb = 0usize;
        for c0 in 0..40320 {
            if bcls[c0] != u16::MAX {
                continue;
            }
            let start = St { c: crate::core::unrank_perm(c0), e: St::ID.e, s: St::ID.s };
            let mut orbit = vec![start];
            bcls[c0] = nb as u16;
            let mut i = 0;
            while i < orbit.len() {
                let s = orbit[i];
                let mut next = vec![corners(&s.apply_move(0)), corners(&s.apply_move(3))];
                for g in &gens {
                    next.push(s.mul(*g));
                }
                for t in next {
                    let r = rank_perm(&t.c);
                    if bcls[r] == u16::MAX {
                        bcls[r] = nb as u16;
                        orbit.push(t);
                    }
                }
                i += 1;
            }
            nb += 1;
        }
        let mut solved = vec![false; 40320];
        for s in &sym8 {
            solved[rank_perm(&s.c)] = true;
        }
        Sec { bcls, nb, ell, solved }
    }
}

/// One reading: L, the extra moves of each section before HTR (first to last), the corner moves of the last
/// section, and the corner cases at the quarter turns folded into a key.
#[derive(Clone, Copy, Default)]
pub struct Read {
    pub q: u8,
    pub l: u8,
    pub lc: u8,
    pub e: [u8; 6],
    pub route: u64,
    /// moves made up to the state with 2 quarter turns left
    pub a2: u8,
    /// skeleton moves of each section before HTR, 3 bits each (first section in the low bits)
    pub shape: u32,
}
impl Read {
    /// Extra moves before the state with 2 quarter turns left, of the setup and of the trigger.
    pub fn pst(&self) -> (u8, u8, u8) {
        let q = self.q as usize;
        (self.e[..q - 2].iter().sum(), self.e[q - 2], self.e[q - 1])
    }
}

/// Read the path `w` (ends with a quarter turn, lands on HTR state `z`) from the state `y`.
pub fn read(sec: &Sec, y: &St, w: &[usize], z: &St) -> Read {
    let mut r = Read::default();
    let mut s = *y;
    let mut g = St::ID;
    let (mut n, mut qi) = (0u8, 0usize);
    let qtot = w.iter().filter(|&&m| is_qt(m)).count();
    let mut route = 1u64;
    for (i, &mv) in w.iter().enumerate() {
        if is_qt(mv) {
            let k = sec.ell[usize::from(qi > 0)][rank_perm(&g.c)];
            assert!(k != 255 && k <= n, "section shorter than its skeleton");
            r.e[qi] = n - k;
            r.shape |= u32::from(k) << (3 * qi);
            r.l += k + 1;
            route = route * 631 + u64::from(sec.bcls[rank_perm(&s.c)]) + 1;
            qi += 1;
            if qtot - qi == 2 {
                r.a2 = i as u8 + 1;
            }
            (g, n) = (St::ID, 0);
            s = s.apply_move(mv);
        } else {
            s = s.apply_move(mv);
            g = g.apply_move(mv);
            n += 1;
        }
    }
    assert!(n == 0 && qi == qtot && s.c == z.c, "path ends with a quarter turn on its HTR state");
    r.q = qtot as u8;
    r.lc = sec.ell[2][rank_perm(&z.inv().c)];
    assert!(r.lc != 255);
    r.l += r.lc;
    r.route = route;
    r
}

/// The reading of a path with any number of quarter turns (`Read` holds at most six sections), for the lists that
/// don't stop at two more quarter turns than the DR: quarter turns, L, the corner moves left, (P, S, T), the corner
/// cases at the quarter turns folded as `read` folds them, and the true pairs right after the last insertion (the
/// state just before the quarter turn that closes the last section with extra moves, or before the last quarter
/// turn when no section has any).  With one quarter turn there is no setup: the extra moves before it are T.
#[derive(Clone, Copy, Default)]
pub struct ReadAny {
    pub q: u8,
    pub l: u8,
    pub lc: u8,
    pub p: u8,
    pub s: u8,
    pub t: u8,
    pub route: u64,
    pub ipairs: u8,
}

/// Read the path `w` (ends with a quarter turn on an HTR state) from the state `y`.
pub fn read_any(sec: &Sec, y: &St, w: &[usize]) -> ReadAny {
    let mut s = *y;
    let mut g = St::ID;
    let (mut n, mut l, mut route) = (0u8, 0u8, 1u64);
    let mut e: Vec<u8> = Vec::with_capacity(8);
    let mut before: Vec<St> = Vec::with_capacity(8);
    for &mv in w {
        if is_qt(mv) {
            let k = sec.ell[usize::from(!e.is_empty())][rank_perm(&g.c)];
            assert!(k != 255 && k <= n, "section shorter than its skeleton");
            e.push(n - k);
            l += k + 1;
            route = route * 631 + u64::from(sec.bcls[rank_perm(&s.c)]) + 1;
            before.push(s);
            (g, n) = (St::ID, 0);
            s = s.apply_move(mv);
        } else {
            s = s.apply_move(mv);
            g = g.apply_move(mv);
            n += 1;
        }
    }
    let q = e.len();
    assert!(n == 0 && q >= 1, "path ends with a quarter turn");
    let lc = sec.ell[2][rank_perm(&s.inv().c)];
    assert!(lc != 255, "path ends on an HTR state");
    let last = (0..q).rev().find(|&j| e[j] > 0).unwrap_or(q - 1);
    let (p, st, t) = if q >= 2 { (e[..q - 2].iter().sum(), e[q - 2], e[q - 1]) } else { (0, 0, e[0]) };
    ReadAny { q: q as u8, l: l + lc, lc, p, s: st, t, route, ipairs: crate::meta::pairs(&before[last]) }
}

/// Read a whole solution (path + finish): (L, extra moves of every section, the finish's last).
pub fn read_solution(sec: &Sec, w: &[usize]) -> (u8, Vec<u8>) {
    let mut g = St::ID;
    let (mut n, mut l, mut first) = (0u8, 0u8, true);
    let mut ex = Vec::new();
    for &mv in w {
        if is_qt(mv) {
            let k = sec.ell[usize::from(!first)][rank_perm(&g.c)];
            ex.push(n - k);
            l += k + 1;
            first = false;
            (g, n) = (St::ID, 0);
        } else {
            g = g.apply_move(mv);
            n += 1;
        }
    }
    let k = sec.ell[2][rank_perm(&g.c)];
    ex.push(n - k);
    (l + k, ex)
}

/// The shortest corner-only path from corner state `c0` that is in corner case `b[i]` (class under U, D turns and
/// symmetry) right before its i-th quarter turn, makes exactly `b.len()` quarter turns and ends on corners that are
/// solved up to a symmetry.  An independent reading of "the skeleton of this route".
pub fn dp_len(md: &Model, sec: &Sec, c0: usize, b: &[u16]) -> u8 {
    fn close(md: &Model, cur: &mut HashMap<usize, u8>) {
        let mut todo: Vec<usize> = cur.keys().copied().collect();
        while let Some(c) = todo.pop() {
            let d = cur[&c];
            for &h in &HALF {
                let c2 = md.core.cmove[h][c] as usize;
                if cur.get(&c2).is_none_or(|&o| o > d + 1) {
                    cur.insert(c2, d + 1);
                    todo.push(c2);
                }
            }
        }
    }
    let mut cur: HashMap<usize, u8> = HashMap::new();
    cur.insert(c0, 0);
    for &bi in b {
        close(md, &mut cur);
        let mut next: HashMap<usize, u8> = HashMap::new();
        for (&c, &d) in &cur {
            if sec.bcls[c] != bi {
                continue;
            }
            for qt in [0usize, 2, 3, 5] {
                let c2 = md.core.cmove[qt][c] as usize;
                let e = next.entry(c2).or_insert(255);
                *e = (*e).min(d + 1);
            }
        }
        cur = next;
    }
    close(md, &mut cur);
    cur.iter().filter(|(&c, _)| sec.solved[c]).map(|(_, &d)| d).min().unwrap_or(255)
}

/// The record of one HTR (50 bytes).
pub struct Out {
    pub dr: u32,
    pub pre2: u32,
    pub route: u64,
    pub side: u8,
    pub q: u8,
    pub kind: u8,
    pub wl: u8,
    pub l: u8,
    pub lc: u8,
    pub e: [u8; 6],
    pub nb: [u8; 4],
    pub total: u8,
    pub tl: u8,
    pub tlen: u8,
    pub te: [u8; 6],
    pub tn: u8,
    pub fam: u8,
    pub a2: u8,
    pub shape: u32,
    /// true pairs and HTR-equivalent pairs in the U and D layers right after the last insertion
    /// (`annot::pairs_after_insertion` on the shortest member, the one (L; e) is read on)
    pub pairs: u8,
    pub hpairs: u8,
}
impl Out {
    pub fn bytes(&self) -> [u8; 50] {
        let mut b = [0u8; 50];
        b[0..4].copy_from_slice(&self.dr.to_le_bytes());
        b[4..8].copy_from_slice(&self.pre2.to_le_bytes());
        b[8..16].copy_from_slice(&self.route.to_le_bytes());
        b[16..22].copy_from_slice(&[self.side, self.q, self.kind, self.wl, self.l, self.lc]);
        b[22..28].copy_from_slice(&self.e);
        b[28..32].copy_from_slice(&self.nb);
        b[32..35].copy_from_slice(&[self.total, self.tl, self.tlen]);
        b[35..41].copy_from_slice(&self.te);
        b[41..44].copy_from_slice(&[self.tn, self.fam, self.a2]);
        b[44..48].copy_from_slice(&self.shape.to_le_bytes());
        b[48..50].copy_from_slice(&[self.pairs, self.hpairs]);
        b
    }
}

fn wvec(a: &[u8; 16], n: u8) -> Vec<usize> {
    a[..n as usize].iter().map(|&m| m as usize).collect()
}

pub struct Tally {
    pub classes: u64,
    pub longer: u64,
    pub fam_eq: u64,
    pub dp_routes: u64,
    pub dp_bad: u64,
    pub mirror: u64,
    pub mirror_bad: u64,
}

/// Every HTR of one DR on both sides, read against its own skeleton.  `deep` adds the two checks.
pub fn one(cx: &Ctx, sec: &Sec, x: &St, dr: u32, deep: bool, t: &mut Tally) -> Vec<Out> {
    let md = cx.md;
    let m = qt_count(md, x);
    let goal = goal_of(m);
    let qmax = (m + 2).min(6);
    let mut out = Vec::new();
    for (side, y) in [(0u8, *x), (1u8, x.inv())] {
        let c0 = rank_perm(&y.c);
        let cl = cx.classes(&y, &Uni { goal, cap_any: 0, qmax });
        let mut keys: Vec<&u64> = cl.keys().collect();
        keys.sort();
        let mut ids2: HashMap<u64, u32> = HashMap::new();
        let mut seen: HashMap<u64, u8> = HashMap::new();
        for k in keys {
            let c: &Cls = &cl[k];
            let w = wvec(&c.w, c.wl);
            let z = md.hg.st[c.z as usize];
            let kind = md.cases[md.hcase[c.z as usize] as usize].kind as usize;
            let r = read(sec, &y, &w, &z);
            assert_eq!(r.lc, LC[kind], "corner moves of the last section = the kind's");
            let fam = md.rem[kind][c.q as usize][c0] + LC[kind];
            assert!(r.l >= fam, "skeleton shorter than the family's shortest corner path");
            assert!(r.l as usize + r.e.iter().map(|&v| v as usize).sum::<usize>() == c.wl as usize + r.lc as usize);
            t.classes += 1;
            t.fam_eq += u64::from(r.l == fam);
            // the member with the best total, read the same way
            let tw = wvec(&c.tw, c.tl);
            let tz = md.hg.st[c.tz as usize];
            let tr = read(sec, &y, &tw, &tz);
            t.longer += u64::from(c.tl != c.wl);
            let n2 = ids2.len() as u32;
            let pre2 = *ids2.entry(cx.im.key(&w[..r.a2 as usize], false)).or_insert(n2);
            if deep {
                if let Some(&l0) = seen.get(&r.route) {
                    assert_eq!(l0, r.l, "one route, one skeleton length");
                } else {
                    seen.insert(r.route, r.l);
                    // the corner cases at the quarter turns, and the shortest corner path through them
                    let mut b = Vec::new();
                    let mut s = y;
                    for &mv in &w {
                        if is_qt(mv) {
                            b.push(sec.bcls[rank_perm(&s.c)]);
                        }
                        s = s.apply_move(mv);
                    }
                    t.dp_routes += 1;
                    if dp_len(md, sec, c0, &b) != r.l {
                        t.dp_bad += 1;
                    }
                }
                if c.total as usize <= goal {
                    // the inverse of the whole solution, read from the inverse state: the mirror image
                    let mut full = tw.clone();
                    full.extend(crate::crisp::ls_finish(md, c.tz));
                    let (l1, e1) = read_solution(sec, &full);
                    let inv: Vec<usize> = full.iter().rev().map(|&mv| crate::core::MOVE_INV[mv]).collect();
                    let (l2, mut e2) = read_solution(sec, &inv);
                    e2.reverse();
                    t.mirror += 1;
                    if l1 != l2 || e1 != e2 || l1 != tr.l {
                        t.mirror_bad += 1;
                    }
                }
            }
            let nb: [u8; 4] = std::array::from_fn(|i| c.lbx[i] - c.wl - r.lc);
            let (pairs, hpairs) = crate::annot::pairs_after_insertion(&y, &w, &r);
            out.push(Out {
                dr,
                pre2,
                route: r.route,
                side,
                q: c.q,
                kind: kind as u8,
                wl: c.wl,
                l: r.l,
                lc: r.lc,
                e: r.e,
                nb,
                total: c.total,
                tl: tr.l,
                tlen: c.tl,
                te: tr.e,
                tn: c.total - c.tl - tr.lc,
                fam,
                a2: r.a2,
                shape: r.shape,
                pairs,
                hpairs,
            });
        }
    }
    out
}

/// The corner cases at the quarter turns of `w` from `y`, folded the way `read` folds them.
fn route_from(sec: &Sec, y: &St, w: &[usize]) -> u64 {
    let (mut s, mut route) = (*y, 1u64);
    for &mv in w {
        if is_qt(mv) {
            route = route * 631 + u64::from(sec.bcls[rank_perm(&s.c)]) + 1;
        }
        s = s.apply_move(mv);
    }
    route
}

/// The NISS rule of the Suggested Meta (Advanced DR Bounding): "If a 3qt+ skeleton begins with a U move, check the
/// forward scramble normally, and NISS after the U instead of checking the full inverse.  If a skeleton ends with U
/// (i.e. has HH corners), then apply (U) and NISS instead of checking the full forward scramble."
///
/// Seen from the side that is not searched in full: its skeleton ends with its last quarter turn, that turn is made
/// first on the other side, and what is left on this side is a DR with one quarter turn fewer and one move less to
/// the goal.  This lists the HTRs of those left-over DRs, on both sides of `x`, as records of the same kind as
/// `one`'s: skeletons with one quarter turn fewer than the DR's own or one more (so the whole skeleton has the DR's
/// own or two more, and 3 at least), read against their own skeleton.
///
/// The turn can go either way; the two left-over DRs are U2 apart, the same paths reach HTR in both, and the two
/// HTRs of a path are U2 apart like the two ways of a last quarter turn, which one class already holds together.
/// It can also be made on the D layer: the left-over DR is then the same up to a turn of both layers together made
/// first, and the same paths reach HTR with their last quarter turn on the other layer.  So the unit is the path's
/// class with the four ways of the turn: its total is the best of them, its bound the smallest, its skeleton the
/// shortest (the readings only differ in the corner moves of the finish).  All four are needed for the total: a
/// path with two quarter turns ends on three of the four HTR states that are a half turn of a layer apart after a U
/// turn, and on the fourth only after a D turn.  In the record the turn made
/// on the other side is counted: `l`, `wl`, `total`, `tl`, `tlen` are one more than the left-over DR's, while `q` and
/// the sections `e`, `shape` are the left-over skeleton's (the whole skeleton has q + 1 quarter turns).
///
/// A path of the left-over DR that is solved at its last quarter turn is not a unit: with the turn made on the other
/// side it ends with two quarter turns of the U/D layers in a row, which is the skeleton two quarter turns shorter.
pub fn rest(cx: &Ctx, sec: &Sec, x: &St, dr: u32) -> Vec<Out> {
    let m = qt_count(cx.md, x);
    let mut out = Vec::new();
    for (side, y) in [(0u8, *x), (1u8, x.inv())] {
        out.extend(rest_side(cx, sec, &y, m, side, dr, false).into_iter().map(|u| u.out));
    }
    out
}

/// A unit of `rest`: the key of its path's class, its record, and (when asked for, and within the goal) its best
/// solution written on its side, the turn made on the other side at the end.
pub struct RestUnit {
    pub key: u64,
    pub out: Out,
    pub sol: Option<Vec<usize>>,
}

/// The units of `rest` on one side: `y` is the DR on that side, `m` its quarter turns.
pub fn rest_side(cx: &Ctx, sec: &Sec, y: &St, m: usize, side: u8, dr: u32, want_sol: bool) -> Vec<RestUnit> {
    let md = cx.md;
    let goal = goal_of(m);
    let qs: Vec<usize> = [m.wrapping_sub(1), m + 1].into_iter().filter(|q| (2..=6).contains(q)).collect();
    let mut out = Vec::new();
    let Some(&qmax) = qs.iter().max() else { return out };
    let uni = Uni { goal: goal - 1, cap_any: 0, qmax };
    {
        let y = *y;
        // this side's solution s = s' t ends with the quarter turn t: y s' = t', so s' solves t y.  The turn is made
        // each way and on each layer (U' y, U y, D' y, D y).  A turn of the D layer leaves the same paths, with their
        // last quarter turn on the other layer, so the classes are the same ones; but with two quarter turns in the
        // path one of the HTR states it can end on is only reached after a D turn, and it can have the shorter finish.
        const TURNS: [usize; 4] = [2, 0, 5, 3];
        let ys = TURNS.map(|t| word(&[t]).mul(y));
        let cls = [cx.classes(&ys[0], &uni), cx.classes(&ys[1], &uni), cx.classes(&ys[2], &uni), cx.classes(&ys[3], &uni)];
        let mut keys: Vec<u64> = cls.iter().flat_map(|c| c.keys()).copied().collect();
        keys.sort();
        keys.dedup();
        let mut ids2: HashMap<u64, u32> = HashMap::new();
        for k in keys {
            // each way the turn can go: the class there (after a quarter turn the DR also has paths with one
            // quarter turn fewer than any skeleton listed here; those are left out)
            let mut ways: Vec<(usize, &Cls, Read, Vec<usize>)> = Vec::new();
            for (d, cl) in cls.iter().enumerate() {
                if let Some(c) = cl.get(&k).filter(|c| qs.contains(&(c.q as usize))) {
                    let w = wvec(&c.w, c.wl);
                    let r = read(sec, &ys[d], &w, &md.hg.st[c.z as usize]);
                    assert!(r.l as usize + r.e.iter().map(|&v| v as usize).sum::<usize>() == c.wl as usize + r.lc as usize);
                    ways.push((d, c, r, w));
                }
            }
            if ways.is_empty() {
                continue;
            }
            let wl = ways.iter().map(|v| v.1.wl).min().unwrap();
            ways.retain(|v| v.1.wl == wl);
            assert!(ways.iter().all(|v| v.2.e == ways[0].2.e && v.2.shape == ways[0].2.shape && v.2.q == ways[0].2.q), "the ways of the turn read one path differently");
            // the member the record is read on: a turn of the U layer where there is one (the ways are in that order)
            let (d, c, r, w) = ways.iter().min_by_key(|v| (v.2.l, v.0 / 2, v.1.total, v.0)).unwrap();
            let lc = r.lc;
            let lbx: [u8; 4] = std::array::from_fn(|i| ways.iter().map(|v| v.1.lbx[i]).min().unwrap());
            let nb: [u8; 4] = std::array::from_fn(|i| lbx[i] - wl - lc);
            // the member with the best total, over the four ways
            let (td, tc) = ways.iter().map(|v| (v.0, v.1)).min_by_key(|(d, c)| (c.total, *d)).unwrap();
            // solved at the path's last quarter turn: that turn and the one made first on the other side are two
            // quarter turns of the U/D layers in a row, so this is the solution of the skeleton two quarter turns
            // shorter (one or two moves shorter once the two are merged), which the full search of the side holds
            if tc.total == tc.tl {
                continue;
            }
            let tw = wvec(&tc.tw, tc.tl);
            let tr = read(sec, &ys[td], &tw, &md.hg.st[tc.tz as usize]);
            let kind = md.cases[md.hcase[c.z as usize] as usize].kind;
            let n2 = ids2.len() as u32;
            let pre2 = *ids2.entry(cx.im.key(&w[..r.a2 as usize], false)).or_insert(n2);
            let (pairs, hpairs) = crate::annot::pairs_after_insertion(&ys[*d], w, r);
            let sol = (want_sol && tc.total as usize + 1 <= goal).then(|| {
                let mut s = tw.clone();
                s.extend(crate::crisp::ls_finish(md, tc.tz));
                s.push(TURNS[td]);
                s
            });
            let rec = Out {
                dr,
                pre2,
                // one skeleton id for the ways of the turn: the corner cases along the path from the first of the
                // DRs of its layer (the two are a half turn of that layer apart, and the same path runs from both)
                route: route_from(sec, &ys[*d / 2 * 2], w),
                side,
                q: c.q,
                kind,
                wl: wl + 1,
                l: r.l + 1,
                lc,
                e: r.e,
                nb,
                total: tc.total + 1,
                tl: tr.l + 1,
                tlen: tc.tl + 1,
                te: tr.e,
                tn: tc.total - tc.tl - tr.lc,
                fam: 0,
                a2: r.a2,
                shape: r.shape,
                pairs,
                hpairs,
            };
            out.push(RestUnit { key: k, out: rec, sol });
        }
    }
    out
}

/// drvar metarest1 "SCRAMBLE" : the left-over DRs of one DR, for each side and each quarter turn made first on the
/// other side (U', U, D', D): quarter turns of the left-over DR, its classes by skeleton quarter turns, and the
/// best total with that turn counted.  A check that the layer of the turn does not matter.
pub fn rest_cmd(md: &Model, rulefile: &str, scr: &str) {
    let mut cx = Ctx::new(md);
    load_rules(&mut cx, rulefile);
    let x = word(&crate::core::parse_moves(scr.as_bytes(), 64).unwrap_or_else(|| fatal!("not DR moves")));
    let m = qt_count(md, &x);
    let goal = goal_of(m);
    let qs: Vec<usize> = [m.wrapping_sub(1), m + 1].into_iter().filter(|q| (2..=6).contains(q)).collect();
    let qmax = *qs.iter().max().unwrap();
    for (side, y) in [("N", x), ("I", x.inv())] {
        for t in [2usize, 0, 5, 3] {
            // this side's solution s' t ends with t: y s' t is solved exactly when (t y) s' is
            let yt = word(&[t]).mul(y);
            let cl = cx.classes(&yt, &Uni { goal: goal - 1, cap_any: 0, qmax });
            let mut by: std::collections::BTreeMap<(u8, u8), usize> = std::collections::BTreeMap::new();
            for c in cl.values().filter(|c| qs.contains(&(c.q as usize))) {
                *by.entry((c.q, c.total + 1)).or_default() += 1;
            }
            let best = by.keys().map(|k| k.1).min();
            let within: Vec<String> = by.iter().filter(|(k, _)| k.1 as usize <= goal).map(|(k, n)| format!("q{} total {}: {n}", k.0, k.1)).collect();
            println!("{side}\tlast {}\tleft-over DR {}qt htr_like {}\tclasses {}\tbest {:?}\t{}", wname(&[t]), qt_count(md, &yt), htr_like(md, &yt), by.values().sum::<usize>(), best, within.join(", "));
            // the within-goal ones written out as solutions of this side: path, finish, and the turn at the end
            let sec = Sec::new();
            for c in cl.values().filter(|c| qs.contains(&(c.q as usize)) && c.total as usize + 1 <= goal) {
                let tw = wvec(&c.tw, c.tl);
                let r = read(&sec, &yt, &tw, &md.hg.st[c.tz as usize]);
                let (p, s, tt) = r.pst();
                // `same`: the path printed (the member with the best total) is the member the record is read on;
                // `first`: skeleton moves before the first quarter turn (0 on normal: the pass is made on inverse)
                println!(
                    "  sol\t{side}\t{}\t{}\t{}\tq {}\tL {}\tP {p} S {s} T {tt} N {}\tbound {}\ttotal {}\tsame {}\tsections {}\tfirst {}",
                    wname(&tw),
                    wname(&crate::crisp::ls_finish(md, c.tz)),
                    wname(&[t]),
                    c.q,
                    r.l + 1,
                    c.total - c.tl - r.lc,
                    c.lbx[1] - c.wl - r.lc,
                    c.total + 1,
                    u8::from(tw == wvec(&c.w, c.wl)),
                    r.e[..c.q as usize].iter().map(|v| v.to_string()).collect::<Vec<_>>().join(","),
                    r.shape & 7
                );
            }
        }
    }
}

/// drvar metarest N SEED M RULEFILE OUT : for the DRs of `metatuple N SEED M`, the HTRs of the left-over DRs of the
/// NISS rule (`rest`), one 50-byte record each.
pub fn run_rest(md: &Model, n: usize, seed: u64, mwant: usize, rulefile: &str, out: &str) {
    use rayon::prelude::*;
    use std::io::Write;
    let mut cx = Ctx::new(md);
    load_rules(&mut cx, rulefile);
    let sec = Sec::new();
    let mut rng = crate::Rng(seed);
    let mut xs = Vec::new();
    while xs.len() < n {
        let x = crate::random_dr(md, &mut rng);
        if qt_count(md, &x) == mwant {
            xs.push(x);
        }
    }
    let mut fb = std::io::BufWriter::new(std::fs::File::create(out).unwrap());
    let t0 = std::time::Instant::now();
    let mut tot = 0u64;
    for (b, chunk) in xs.chunks(64).enumerate() {
        let res: Vec<Vec<Out>> = chunk.par_iter().enumerate().map(|(i, x)| rest(&cx, &sec, x, (b * 64 + i) as u32)).collect();
        for recs in res {
            tot += recs.len() as u64;
            for r in recs {
                fb.write_all(&r.bytes()).unwrap();
            }
        }
        eprintln!("{} / {n}  {:.0}s", (b * 64 + chunk.len()).min(n), t0.elapsed().as_secs_f64());
    }
    println!("HTRs of the left-over DRs\t{tot}");
}

/// The N of up to four rules for each case, from a file with one line per case (order of `metacases`).
pub fn load_rules(cx: &mut Ctx, rulefile: &str) {
    let txt = std::fs::read_to_string(rulefile).unwrap_or_else(|e| fatal!("{rulefile}: {e}"));
    let rows: Vec<Vec<u8>> = txt.lines().map(|l| l.split('\t').map(|v| v.trim().parse::<u8>().unwrap_or_else(|_| fatal!("{rulefile}: not a number: {l}"))).collect()).collect();
    assert_eq!(rows.len(), cx.md.cases.len(), "one line per case");
    let k = rows[0].len();
    assert!((1..=4).contains(&k) && rows.iter().all(|r| r.len() == k));
    cx.xpen = rows.iter().map(|r| std::array::from_fn(|i| r[i.min(k - 1)])).collect();
}

/// drvar metatuple N SEED M RULEFILE OUT [DEEP] : the HTRs of `metarun N SEED M` (corner bound within the goal),
/// one 50-byte record each; the two checks of the reading run on the first DEEP DRs (default 100).
pub fn run(md: &Model, n: usize, seed: u64, mwant: usize, rulefile: &str, out: &str, deep: usize) {
    use rayon::prelude::*;
    use std::io::Write;
    let mut cx = Ctx::new(md);
    load_rules(&mut cx, rulefile);
    let sec = Sec::new();
    eprintln!("{} corner cases at a quarter turn", sec.nb);
    // every HTR state: the corner moves of its finish are the kind's
    for (i, s) in md.hg.st.iter().enumerate() {
        let kind = md.cases[md.hcase[i] as usize].kind as usize;
        assert_eq!(sec.ell[2][rank_perm(&s.inv().c)], LC[kind]);
    }
    let mut rng = crate::Rng(seed);
    let mut xs = Vec::new();
    while xs.len() < n {
        let x = crate::random_dr(md, &mut rng);
        if qt_count(md, &x) == mwant {
            xs.push(x);
        }
    }
    let mut fb = std::io::BufWriter::new(std::fs::File::create(out).unwrap());
    let mut tot = Tally { classes: 0, longer: 0, fam_eq: 0, dp_routes: 0, dp_bad: 0, mirror: 0, mirror_bad: 0 };
    let t0 = std::time::Instant::now();
    for (b, chunk) in xs.chunks(64).enumerate() {
        let res: Vec<(Vec<Out>, Tally)> = chunk
            .par_iter()
            .enumerate()
            .map(|(i, x)| {
                let dr = b * 64 + i;
                let mut t = Tally { classes: 0, longer: 0, fam_eq: 0, dp_routes: 0, dp_bad: 0, mirror: 0, mirror_bad: 0 };
                let o = one(&cx, &sec, x, dr as u32, dr < deep, &mut t);
                (o, t)
            })
            .collect();
        for (recs, t) in res {
            for r in recs {
                fb.write_all(&r.bytes()).unwrap();
            }
            tot.classes += t.classes;
            tot.longer += t.longer;
            tot.fam_eq += t.fam_eq;
            tot.dp_routes += t.dp_routes;
            tot.dp_bad += t.dp_bad;
            tot.mirror += t.mirror;
            tot.mirror_bad += t.mirror_bad;
        }
        eprintln!("{} / {n}  {:.0}s", (b * 64 + chunk.len()).min(n), t0.elapsed().as_secs_f64());
    }
    println!("HTRs\t{}", tot.classes);
    println!("skeleton as long as the shortest corner path of its (quarter turns, kind) family\t{}", tot.fam_eq);
    println!("best member longer than the shortest\t{}", tot.longer);
    println!("routes checked against the shortest corner path through the same corner cases\t{}\tdiffer\t{}", tot.dp_routes, tot.dp_bad);
    println!("within-goal solutions read on both sides\t{}\tnot mirror images\t{}", tot.mirror, tot.mirror_bad);
}

/// drvar metax2 "SCRAMBLE" [M] : every HTR of one DR read against its own skeleton, one line each.
