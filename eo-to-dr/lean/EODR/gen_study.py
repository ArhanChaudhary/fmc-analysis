#!/usr/bin/env python3
"""Writes EODR/Study.lean: four output files of the research, copied verbatim into Lean string literals, so that
the theorems `*_matches_study` compare what Lean computes with exactly what the research wrote.

    research/out/eo_axis.tsv            eodrtools eo axis      (one-axis EO: per state bad, optimal, n0..n8)
    research/out/eo_layouts.tsv         eodrtools eo layouts   (bad-edge triples)
    research/out/eodr_exact.tsv         eodrtools eodr exact   (EO -> DR per case and option)
    research/out/eo0_hist_eo-fb_dr.txt  eodrtools extract      (histogram of the eo = 0 part of eo-fb_dr.u8)

Run from this directory:   python3 gen_study.py      (it must come out unchanged)"""
import os
here = os.path.dirname(os.path.abspath(__file__))
out_dir = os.path.join(here, '..', '..', 'research', 'out')
FILES = [('EO_AXIS_TSV', 'eo_axis.tsv'), ('EO_LAYOUTS_TSV', 'eo_layouts.tsv'),
         ('EODR_EXACT_TSV', 'eodr_exact.tsv'), ('EO0_HIST_EO_FB_DR_TXT', 'eo0_hist_eo-fb_dr.txt')]
lines = ['/-',
         '  EODR.Study — GENERATED by `gen_study.py`, do not edit: four output files of the research, verbatim.',
         '  Only the theorems named `…_matches_study` read them.',
         '-/', '', 'namespace EODR', 'namespace study', '']
for name, fn in FILES:
    txt = open(os.path.join(out_dir, fn)).read()
    assert '"#' not in txt
    lines += [f'/-- research/out/{fn}, verbatim. -/', f'def {name} : String := r#"{txt}"#', '']
lines += ['end study', 'end EODR', '']
open(os.path.join(here, 'EODR', 'Study.lean'), 'w').write('\n'.join(lines))
print('wrote EODR/Study.lean')
